"""Golden CIDs: fixed inputs with the CID the fixed IPFS profile gives them (`cid.py`).

`golden/cid-vectors.json` is the committed reference and `test/content/tooling/CidGoldenData.sol`
is GENERATED from it, so Foundry can check that `WorkRecords.addLocator` accepts every CID as an
`ipfs://` locator and that Solidity re-derives each single-block (raw) CID from the SHA-256 of
its bytes. `python -m tools.content golden --write` regenerates both; `--check` fails if either is
stale.

Provenance. Two vectors are published answers: the empty file and `hello world`, kubo's
well-known CIDv1 raw blocks (`hello world` is also an IPIP-0499 test vector). The others are
computed by `cid.py`, whose encoding `test_cid.py` checks byte for byte against the root blocks of
IPIP-0499's own fixtures (`golden/ipip-0499-blocks.json`: kubo's 174-link node and its rebalanced
two-level root among them) and whose layout it checks against an independent statement of the
balanced layout. `test_cid.py` also compares every vector with kubo whenever an `ipfs` binary is
on the PATH (the test is skipped otherwise).

Inputs are cheap to rebuild at any size: `pattern(length)` is the concatenation of 262,144-byte
chunks, chunk `k` being `k` as four big-endian bytes followed by bytes 4 to 262,143 of
`bytes(range(256)) * 1024`, truncated to `length`, so every chunk differs from the others.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from .cid import CHUNK_SIZE, MAX_LINKS, cid_of_bytes, locator_accepted

ROOT = Path(__file__).resolve().parents[2]
VECTORS_PATH = Path(__file__).resolve().parent / "golden" / "cid-vectors.json"
SOLIDITY_PATH = ROOT / "test" / "content" / "tooling" / "CidGoldenData.sol"
SCHEMA = "6529-works/cid-golden/v1"

_BLOCK = bytes(range(256)) * (CHUNK_SIZE // 256)

# name, input (bytes literal, or a pattern length), and the published CID where one exists.
SPECS: tuple[tuple[str, bytes | int, str | None], ...] = (
    ("empty", b"", "bafkreihdwdcefgh4dqkjv67uzcmw7ojee6xedzdetojuzjevtenxquvyku"),
    ("hello-world", b"hello world", "bafkreifzjut3te2nhyekklss27nh3k72ysco7y32koao5eei66wof36n5e"),
    ("one-chunk", CHUNK_SIZE, None),
    ("one-chunk-plus-one", CHUNK_SIZE + 1, None),
    ("three-chunks-and-a-tail", 3 * CHUNK_SIZE + 1000, None),
    ("one-full-node", MAX_LINKS * CHUNK_SIZE, None),
    ("two-levels", (MAX_LINKS + 1) * CHUNK_SIZE, None),
)


def pattern(length: int) -> bytes:
    """Distinct 262,144-byte chunks: `k` (four bytes, big-endian) then the rest of `_BLOCK`."""
    count = -(-length // CHUNK_SIZE)
    return b"".join(k.to_bytes(4, "big") + _BLOCK[4:] for k in range(count))[:length]


def spec_input(spec: tuple[str, bytes | int, str | None]) -> bytes:
    source = spec[1]
    return source if isinstance(source, bytes) else pattern(source)


def build() -> dict[str, Any]:
    vectors = []
    for spec in SPECS:
        data = spec_input(spec)
        result = cid_of_bytes(data)
        vector: dict[str, Any] = {
            "name": spec[0],
            "size": result.size,
            "chunks": result.chunks,
            "depth": result.depth,
            "cid": result.cid,
            "sha256": "0x" + hashlib.sha256(data).hexdigest(),
        }
        if isinstance(spec[1], bytes):
            vector["input"] = {"kind": "literal", "hex": "0x" + spec[1].hex()}
        else:
            vector["input"] = {"kind": "pattern", "length": spec[1]}
        vector["provenance"] = "published kubo CID" if spec[2] else "computed by tools/content/cid.py"
        vectors.append(vector)
    return {
        "schema": SCHEMA,
        "profile": {
            "cidVersion": 1,
            "hash": "sha2-256",
            "rawLeaves": True,
            "chunker": f"size-{CHUNK_SIZE}",
            "layout": "balanced",
            "maxLinks": MAX_LINKS,
            "multibase": "base32",
        },
        "vectors": vectors,
    }


def render_solidity(document: dict[str, Any]) -> str:
    rows = []
    for i, v in enumerate(document["vectors"]):
        raw = v["depth"] == 0
        rows.append(
            f'        out[{i}] = Vector("{v["name"]}", "ipfs://{v["cid"]}", {v["size"]}, '
            f'{"true" if raw else "false"}, {v["sha256"]});'
        )
    body = "\n".join(rows)
    return f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// GENERATED by `python -m tools.content golden --write` from tools/content/golden/cid-vectors.json.
// Do not edit by hand: `--check` (and the Python tests) fail if this file is stale.

/// @dev The fixed IPFS profile's CIDs as `tools/content/cid.py` computes them (ADR 0001 section 8).
///      `CidGolden.t.sol` checks that `WorkRecords` accepts each as an `ipfs://` locator, and that
///      Solidity re-derives every single-block (raw) CID from the SHA-256 of its bytes.
// forgefmt: disable-start
library CidGoldenData {{
    /// @param raw The file is one raw block, so its CID is `bafkrei` and the digest is `sha256`;
    ///        otherwise its root is a dag-pb node (`bafybei`).
    /// @param sha256 The SHA-256 of the whole file.
    struct Vector {{
        string name;
        string uri;
        uint256 size;
        bool raw;
        bytes32 sha256;
    }}

    function vectors() internal pure returns (Vector[] memory out) {{
        out = new Vector[]({len(document["vectors"])});
{body}
    }}
}}
// forgefmt: disable-end
"""


def check() -> list[str]:
    """Every way the committed CID vectors or their Solidity data can be wrong or stale."""
    problems: list[str] = []
    try:
        committed = json.loads(VECTORS_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"cannot read {VECTORS_PATH.name}: {exc}"]
    expected = build()
    if committed != expected:
        problems.append(f"{VECTORS_PATH.name} differs from what cid.py computes: run `golden --write`")
    for spec, v in zip(SPECS, expected["vectors"]):
        if spec[2] is not None and v["cid"] != spec[2]:
            problems.append(f"{spec[0]}: cid.py gives {v['cid']}, kubo gives {spec[2]}")
        if not locator_accepted("ipfs://" + v["cid"]):
            problems.append(f"{spec[0]}: WorkRecords would refuse ipfs://{v['cid']}")
    try:
        if SOLIDITY_PATH.read_text(encoding="utf-8") != render_solidity(committed):
            problems.append(f"{SOLIDITY_PATH.name} is stale: run `golden --write`")
    except OSError as exc:
        problems.append(f"cannot read {SOLIDITY_PATH.name}: {exc}")
    return problems


def write() -> None:
    document = build()
    VECTORS_PATH.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")
    SOLIDITY_PATH.write_text(render_solidity(document), encoding="utf-8", newline="\n")
